"""Final pilot report. Every number is read from the JSON files the earlier stages produced;
nothing is typed by hand except the prose and the (clearly labelled) risk list.

Usage: python scripts/make_pilot_report.py   ->  reports/pilot_report.md
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R, M = ROOT / "reports", ROOT / "data" / "manifests"


def J(p):
    p = Path(p)
    return json.loads(p.read_text()) if p.exists() else None


def table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows] + [""]


def main():
    s1, s2, lk = J(M / "stage1_manifest.json"), J(R / "stage2_disagreement.json"), J(R / "stage3_leakage.json")
    ed, sel, pw = J(R / "stage3_edits.json"), J(R / "stage3_selection.json"), J(R / "stage4_power.json")
    # Stage 5 files (fixed answer format, fp16, grid written by the script) take priority over the Stage 4 ones
    pick = lambda n: J(R / "stage5" / n) or J(R / "stage4" / n)
    zs, gr, co = pick("zero_shot.json"), pick("grid.json"), pick("cost_extrapolation.json")
    zs4, dev = J(R / "stage4/zero_shot.json"), J(R / "stage5/dev_format.json")
    stage5_zs = J(R / "stage5/zero_shot.json") is not None
    ans = J(R / "answer_stats_tuned.json")
    L = ["# SIFT-VQA pilot report", "",
         "**Every number below is a PILOT number produced by code in this repo (generated by `scripts/make_pilot_report.py` from `reports/*.json`).** "
         "The pilot is a pipeline smoke test. It contains no fine-tuned model result and is NOT evidence for or against the hypothesis. "
         "Items marked ASSUMED are inputs, not measurements.", ""]

    L += ["## 1. Pool", f"- Scenes: {s1['n_scenes']}, questions: {s1['n_questions']}; per template: `{s1['template_counts']}`.",
          f"- Label audit (pixel-based recount + second implementation): {s1['label_audit_mismatches']} mismatches.",
          f"- Shortcuts file SHA-256: `{s2['shortcuts_sha256']}`.", ""]
    L += ["## 2. Answer balance (measured, tuned generator)"]
    if ans:
        L += [f"- `{t}`: `{json.dumps(v)[:300]}`" for t, v in ans.items()]
    L += [""]

    L += ["## 3. Disagreement (d=1) by stratum", f"- Pool d=1 rate {s2['d1_rate_pool_pct']}%; on shortcut-applicable questions (count, exists) {s2['d1_rate_shortcut_applicable_pct']}%.", ""]
    L += table(["shortcut", "n applicable", "agrees with intended %", "d=1 %"],
               [[k, v["n_applicable"], v["agree_pct_of_applicable"], v["d1_pct_of_applicable"]] for k, v in s2["shortcut_agreement"].items()])
    L += table(["template", "n", "d=1", "d=1 %"], [[t, v["n"], v["d1"], v["d1_pct"]] for t, v in s2["d1_by_template"].items()])
    L += ["By answer (count_cs): " + ", ".join(f"{a}: {v['d1_pct']}% of {v['n']}" for a, v in s2["d1_by_template_and_answer"]["count_cs"].items()),
          "By number of objects (count_cs): " + ", ".join(f"{k}: {v['d1_pct']}%" for k, v in s2["d1_by_n_objects"]["count_cs"].items()), ""]
    lc = s2["label_confound"]
    L += ["### Label confound (measured)",
          f"- exists_cs: all {s2['exists_d1_all_answer_no']['n_d1_with_answer_no']} of {s2['exists_d1_all_answer_no']['n_d1']} d=1 questions have answer \"no\" "
          f"(Cramér's V {lc['exists_cs']['cramers_v']}); d alone predicts the answer with {lc['exists_cs']['acc_predicting_answer_from_d_alone_pct']}% accuracy vs {lc['exists_cs']['acc_majority_answer_alone_pct']}% majority.",
          f"- count_cs: Cramér's V {lc['count_cs']['cramers_v']}; d alone {lc['count_cs']['acc_predicting_answer_from_d_alone_pct']}% vs {lc['count_cs']['acc_majority_answer_alone_pct']}% majority.",
          f"- corr(d, n_objects) = {round(s2['difficulty_correlation']['corr_d_vs_n_objects_(shortcut-applicable)'], 3)}.",
          "- This is structural (dropping a filter can only enlarge the matching set). It is handled by answer quotas in the selectors, not removed.", ""]

    L += ["## 4. Splits, leakage and baselines (measured)"]
    L += table(["split", "scenes", "questions"], [[k, v["scenes"], v["questions"]] for k, v in lk["split_sizes"].items()])
    so = lk["signature_overlap"]
    L += [f"- Held-out signature `{so['held_out_signature']}`: in train {so['held_out_in_train']}, pool {so['held_out_in_pool']}, test {so['held_out_in_test']}.",
          f"- Scene-group overlap `{lk['scene_group_overlap_counts']}`; exact duplicate scenes across splits {lk['duplicate_scenes']['exact_duplicate_scenes_across_splits']}; duplicate questions {lk['duplicate_questions_across_splits']}.",
          f"- Question-only majority baselines on test: seen {lk['question_only_baseline']['per_template_majority']['seen_acc_pct']}%, held-out {lk['question_only_baseline']['per_template_majority']['held_out_acc_pct']}%.",
          f"- Shuffled-scene oracle (model-free): {lk['shuffled_scene_oracle_acc_pct']}.",
          f"- Paired visual edits: {ed['n_paired']} of {ed['n_test_questions']} test questions; {ed['audit_mismatches_on_edited_images']} audit mismatches; relevant edits changed the answer in {ed['relevant_answer_changed']}, irrelevant kept it in {ed['irrelevant_answer_same']}.", ""]

    L += ["## 5. Selectors (budget %d, seeds %s)" % (sel["budget"], sel["seeds"])]
    for mode, m in sel["modes"].items():
        ag = m["aggregate_over_seeds"]
        L += [f"### exists_mode = {mode}"]
        L += table(["arm", "d=1 % (all)", "d=1 % (count+exists)", "count d=1 %", "exists d=1 %", "mean objects (count)"],
                   [[a, v["d1_share_all_pct"]["mean"], v["d1_share_count_exists_pct"]["mean"],
                     v["by_template"]["count_cs"]["d1_share_pct"]["mean"], v["by_template"]["exists_cs"]["d1_share_pct"]["mean"],
                     v["by_template"]["count_cs"]["mean_n_objects"]["mean"]]
                    for a, v in ag.items() if "d1_share_all_pct" in v])
        L += [f"Label-count checks all seeds: `{m['checks_all_seeds'][0]}`", ""]
    wd = sel["weak_contrast_diagnostics"]
    L += ["### Contrast diagnostics (measured, options not implemented)",
          f"- Strict d (both count shortcuts disagree): {wd['strict_d_both_shortcuts_disagree']['pool_n']} of {wd['count_pool_n']} pool count questions; "
          f"would be about {wd['strict_d_would_be_short_by_examples_per_seed_(sum over answer cells)']} examples short per seed.",
          "- Count arms: " + "; ".join(f"{k}: gap {v['mean_abs_gap']}, d=1 {v['d1_pct']}%, objects {v['mean_n_objects']}" for k, v in wd["count_arms_mean_over_seeds"].items()), ""]

    L += ["## 5b. Answer-format study on the DEV set (train split; the test set was not used to choose anything)"]
    if dev:
        L += [f"dev n = {dev['dev_set']['n']}; no compare_cs in the dev set (ASSUMED to behave like the other yes/no templates); dtype {dev['dtype']}."]
        L += table(["run", "macro acc %", "per template", "wrong-format %", "sec/item"],
                   [[k, v["macro_acc_pct"], v["acc_by_template_pct"], v["wrong_format_pct"], v["sec_per_item"]] for k, v in dev["runs"].items()])
        if "selection" in dev:
            L += [f"Chosen: `{dev['selection']['method']['chosen']}` at {dev['selection']['resolution']['chosen']} px. Rule: {dev['selection']['rule']}. "
                  "`legacy` (old one-size suffix, free generation) is a diagnostic only.", ""]
    else:
        L += ["NOT RUN yet (needs the GPU notebook).", ""]

    L += ["## 6. Headroom: frozen model on the held-out set (one greedy run)"]
    if zs:
        p, j = zs["plain_accuracy_all_questions"], zs["joint_score_paired_subset"]
        L += [f"Model `{zs['model']}`, {zs['resolution']} px, method `{zs.get('method', 'old one-size suffix (Stage 4)')}`, dtype `{zs.get('dtype', 'auto (probably bf16 on T4; not recorded)')}`.",
              f"- Plain accuracy, all questions: held-out {p['held_out_pct']}% (n={p['n_held_out']}), seen {p['seen_pct']}% (n={p['n_seen']}); by template `{p['by_template_pct']}`.",
              f"- Joint score, paired subset: held-out {j['held_out']['joint_pct']}% (n={j['held_out']['n_paired']}), seen {j['seen']['joint_pct']}% (n={j['seen']['n_paired']}).",
              f"- Shuffled-image control: held-out {zs['shuffled_image_baseline']['held_out_pct']}%, seen {zs['shuffled_image_baseline']['seen_pct']}%.",
              ("- Wrong-format rate with the chosen method: %s%%." % zs.get("wrong_format_pct") if stage5_zs else
               "- Caveat: replies like `0` or `Yes, 1` to yes/no questions are scored wrong, so low exists/compare accuracy may be answer-format failure, not ability (fixed in Stage 5; rerun pending)."), ""]
        if stage5_zs and zs4:
            a, b = zs["plain_accuracy_all_questions"]["by_template_pct"], zs4["plain_accuracy_all_questions"]["by_template_pct"]
            L += ["Before (Stage 4 format) vs after (Stage 5), plain accuracy by template: " + "; ".join(f"{t}: {b[t]} -> {a[t]}" for t in a), ""]
        cc = zs["plain_accuracy_all_questions"]["by_template_pct"].get("count_cs")
        if cc is not None and cc >= 90:
            L += [f"**Count headroom:** frozen count_cs accuracy is {cc}%, so count has little room to improve. This is a finding to raise with the supervisor; no workaround was applied.", ""]
    else:
        L += ["NOT RUN.", ""]

    L += ["## 7. Memory and speed (measured on the GPU named in the file)"]
    if gr and "TRANSCRIBED" in gr:
        L += ["NOTE: this grid was transcribed by hand from a Colab log (original file lost); its dtype label was an assumption. Rerun pending.", ""]
    elif gr:
        L += [f"dtype `{gr.get('dtype')}`, GPU `{gr['env'].get('gpu')}`, complete={gr.get('complete')}.", ""]
    if gr:
        L += table(["resolution", "batch", "status", "peak GB", "sec/step"],
                   [[r["resolution"], r["batch"], r["status"], r.get("peak_mem_gb", ""), r.get("sec_per_step_incl_preprocess", "")] for r in gr["rows"]])
    if co:
        b = co["based_on"]
        L += [f"Zero-shot eval speed {b['sec_per_eval_example']} s/example ({b['sec_per_eval_example_source']}). Budget {co['budget_hours']} GPU-hours. "
              f"Extrapolation uses {b['resolution']} px, batch {b['batch']}, {b['sec_per_step']} s/step.", ""]
        L += table(["scenario", "GPU-hours", "% of budget", "fits"], [[s["name"], s["total_gpu_hours"], s["share_of_budget_pct"], s["fits_budget"]] for s in co["scenarios"]])
        L += ["T4 numbers do not transfer to other GPUs.", ""]
        if co.get("previous_stage4_scenarios_for_comparison"):
            L += ["Previous (Stage 4, 448 px, old grid) vs now, GPU-hours: " + "; ".join(
                f"{o['name'][:40]}: {o['total_gpu_hours']} -> {n['total_gpu_hours']}" for o, n in zip(co["previous_stage4_scenarios_for_comparison"], co["scenarios"])), ""]

    pr = pw["proposal"]
    L += ["## 8. Held-out test-size proposal (power calculation; psi and seed sd are ASSUMED)",
          f"- Target: 3-point gain, alpha {pw['assumed_inputs']['alpha']}, power {pw['assumed_inputs']['power']}. Headline case `{pw['assumed_inputs']['headline_case']}`.",
          f"- Needed: {pr['plain_questions_needed']} plain questions, {pr['joint_paired_questions_needed']} paired questions, i.e. {pr['held_out_test_scenes_proposed']} held-out scenes (now 500; {pr['scenes_needed_if_paired_coverage_were_0.9']} if paired coverage were 0.9).",
          f"- Current test set detects about {pw['min_detectable_gain_points_at_80pct_power']['plain_n=500_sigma=0.01_k=5']} points (plain) and {pw['min_detectable_gain_points_at_80pct_power']['joint_n=355_sigma=0.01_k=5']} points (joint) at 80% power.",
          f"- Seed-noise ceilings (sd, points): `{pr['seed_noise_ceiling_points']}`.",
          "- Plain accuracy (all questions) and joint score (paired subset) are separate endpoints.", ""]

    L += ["## 9. What could break the plan",
          "Items below come from the measurements above unless marked otherwise.", "",
          "1. **Exists label confound.** d=1 implies \"no\" for exists (structural). Quotas equalise labels across arms, but any exists effect is entangled with the selector. A fixed-shared-base mode exists behind a config switch.",
          "2. **Weak shortcut contrast on count.** Matched random already has a high d=1 share on count (see section 5: shortcut arm 100% vs matched random about 70%), so the contrast is modest. Strict or graded d are options, not implemented; graded d also raises object count (a difficulty confound).",
          "3. **Underpowered test set.** 500 held-out scenes detect only about 6 to 8 points; the proposal is several thousand scenes. If seed sd exceeds the ceiling, no test size works (sd is ASSUMED until measured).",
          "4. **GPU budget.** On a T4 only batch 1 at 448 px fits; the multi-seed plan exceeds the 20 GPU-hour budget (section 7). Evaluation dominates cost. A faster GPU or a smaller evaluation is needed.",
          "5. **Training code never run end to end on a GPU.** `tiny-finetune` is untested on a GPU. Stage 5 reviewed it (loss mask, fp32 LoRA adapters with fp16 GradScaler, seeds, manifest checks) with CPU tests only.",
          ("6. **Answer format.** Fixed in Stage 5 (per-template instruction or choice scoring, chosen on the dev set); see sections 5b and 6." if stage5_zs else
          "6. **Answer-format failures.** Stage 4 outputs like `0` for yes/no questions were scored wrong; the Stage 5 fix is written but its GPU run is pending."),
          "7. **Synthetic-to-real gap and one operation combination.** One held-out combination (compare_cs) in simple 2D scenes; no claim beyond this pilot (not measured here).",
          "8. **Library drift.** Colab ships newer transformers/peft than local; `torchao` had to be uninstalled. `requirements-gpu.txt` pins transformers and peft only (the two measured); the rest is pinned after `scripts/freeze_env.py` runs on the GPU machine.",
          "9. **dtype.** The Stage 4 runs probably used emulated bf16 on the T4 (torch reported bf16 as supported); Stage 5 forces fp16 below compute capability 8.0. Stage 4 speed numbers may therefore not match Stage 5.", ""]
    (R / "pilot_report.md").write_text("\n".join(L))
    print(f"wrote {R / 'pilot_report.md'}")


if __name__ == "__main__":
    main()
