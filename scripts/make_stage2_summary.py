"""Build reports/stage2_summary.md (before/after tables) from the measured JSON files only."""
import json
from siftvqa.config import ROOT

R = ROOT / "reports"
load = lambda n: json.load(open(R / n))
b, a = load("stage2_before_tuning.json"), load("stage2_disagreement.json")
sb, sa = load("answer_stats_after.json"), load("answer_stats_tuned.json")
IN = lambda x: "yes" if 60 <= x <= 75 else "NO"
L = ["# Stage 2 summary (pilot numbers, generated by scripts/make_stage2_summary.py)", "",
     f"Shortcuts file SHA-256: `{a['shortcuts_sha256']}`. Before = first generator fix (palette 2-3 colours/shapes, focus 0.4); after = tuned generator. Same pool seed.", "",
     "## Per shortcut (questions the shortcut applies to). Target: agreement 60-75% (d=1 25-40%)", "",
     "| Shortcut | n | agree before | agree after | d=1 before | d=1 after | in band |", "|---|---|---|---|---|---|---|"]
for k, v in a["shortcut_agreement"].items():
    o = b["shortcut_agreement"][k]
    L.append(f"| {k} | {v['n_applicable']} | {o['agree_pct_of_applicable']}% | {v['agree_pct_of_applicable']}% | {o['d1_pct_of_applicable']}% | {v['d1_pct_of_applicable']}% | {IN(v['agree_pct_of_applicable'])} |")
L += ["", "## d=1 per template and combined (d = any applicable shortcut disagrees)", "", "| Template | n | d=1 before | d=1 after |", "|---|---|---|---|"]
for t, v in a["d1_by_template"].items():
    L.append(f"| {t} | {v['n']} | {b['d1_by_template'][t]['d1_pct']}% | {v['d1_pct']}% |")
cb, ca = b["combined_count_exists"] if "combined_count_exists" in b else None, a["combined_count_exists"]
L.append(f"| count+exists combined | {ca['n']} | {b['d1_rate_shortcut_applicable_pct']}% | {ca['d1_pct']}% |")
L.append(f"| whole pool (incl. comparisons, d=0 by construction) | {a['n_questions']} | {b['d1_rate_pool_pct']}% | {a['d1_rate_pool_pct']}% |")
L += ["", "## Answer distribution and majority baseline (before = first generator fix, after = tuned)", "", "| Template | before | before majority | after | after majority |", "|---|---|---|---|---|"]
for t in sa:
    L.append(f"| {t} | {sb[t]['dist']} | {sb[t]['majority_baseline']*100:.1f}% | {sa[t]['dist']} | {sa[t]['majority_baseline']*100:.1f}% |")
q = a["quota_feasibility"]
L += ["", f"## Selection inputs (exists_mode = `{q['exists_mode']}`)", "",
      f"- count d=1 examples available per answer value: {q['count_d1_available_by_answer']} (all count answers: {q['count_answer_dist_all']}).",
      f"- exists: d=1 (all answer 'no'): {q['exists_d1_no']}; d=0 'yes' available to fill the yes quota: {q['exists_d0_yes']}; d=0 'no': {q['exists_d0_no']}.", "",
      "## Label confound after tuning", ""]
for t, v in a["label_confound"].items():
    L.append(f"- {t}: Cramer's V {v['cramers_v']}, MI {v['mutual_info_bits']} bits; predicting the answer from d alone = {v['acc_predicting_answer_from_d_alone_pct']}% vs majority {v['acc_majority_answer_alone_pct']}%; answers when d=1: {v['answer_dist_when_d1']}.")
e = a["exists_d1_all_answer_no"]
L.append(f"- exists d=1 with answer 'no': {e['n_d1_with_answer_no']} of {e['n_d1']} (structural; handled by Option A quotas in Stage 3).")
(R / "stage2_summary.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
